package cargo

import (
	"testing"

	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"
)

const (
	cratesIOGit      = "registry+https://github.com/rust-lang/crates.io-index"
	cratesIOSparse   = "sparse+https://index.crates.io/"
	itoaChecksum     = "49f1f14873335454500d59611f1cf4a4b0f786f9ac11f4312a78e4cf2566695b"
	serdeChecksum    = "25dd9975e68d0cb5aa1120c288333fc98731bd1dd12f561e468ea4728c042b89"
	lazyStaticSHA256 = "bbd2bcb4c963f2ddae06a2efc7e9f3591312473c50c6685e1f298068316e66fe"
)

func TestParseLockFile_V4(t *testing.T) {
	data := []byte(`# This file is automatically @generated by Cargo.
version = 4

[[package]]
name = "itoa"
version = "1.0.11"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "49f1f14873335454500d59611f1cf4a4b0f786f9ac11f4312a78e4cf2566695b"

[[package]]
name = "my-app"
version = "0.1.0"
dependencies = [
 "itoa",
]

[[package]]
name = "gitdep"
version = "0.2.0"
source = "git+https://github.com/example/gitdep?branch=main#0123456789abcdef"
`)

	pkgs, err := parseLockFile(data)
	require.NoError(t, err)
	assert.Equal(t, []lockPackage{
		{Name: "itoa", Version: "1.0.11", Source: cratesIOGit, Checksum: itoaChecksum},
		{Name: "my-app", Version: "0.1.0"},
		{Name: "gitdep", Version: "0.2.0", Source: "git+https://github.com/example/gitdep?branch=main#0123456789abcdef"},
	}, pkgs)
}

