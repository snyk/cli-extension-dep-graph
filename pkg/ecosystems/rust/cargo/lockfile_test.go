// Version 1 lockfiles (cargo before 1.41) keep checksums in a [metadata] table
// keyed "checksum <name> <version> (<source>)" instead of on each package.
func TestParseLockFile_V1MetadataTable(t *testing.T) {
	data := []byte(`[[package]]
name = "itoa"
version = "1.0.11"
source = "registry+https://github.com/rust-lang/crates.io-index"

[[package]]
name = "my-app"
version = "0.1.0"
dependencies = [
 "itoa 1.0.11 (registry+https://github.com/rust-lang/crates.io-index)",
]

[[package]]
name = "serde"
version = "1.0.193"
source = "registry+https://github.com/rust-lang/crates.io-index"

[metadata]
"checksum itoa 1.0.11 (registry+https://github.com/rust-lang/crates.io-index)" = "49f1f14873335454500d59611f1cf4a4b0f786f9ac11f4312a78e4cf2566695b"
"checksum serde 1.0.193 (registry+https://github.com/rust-lang/crates.io-index)" = "<none>"
"not-a-checksum key" = "ignored"
`)

	pkgs, err := parseLockFile(data)
	require.NoError(t, err)
	assert.Equal(t, []lockPackage{
		{Name: "itoa", Version: "1.0.11", Source: cratesIOGit, Checksum: itoaChecksum},
		{Name: "my-app", Version: "0.1.0"},
		{Name: "serde", Version: "1.0.193", Source: cratesIOGit},
	}, pkgs)
}

func TestParseLockFile_Malformed(t *testing.T) {
	_, err := parseLockFile([]byte("[[package]\nname = "))
	require.Error(t, err)
}

func TestParseLockFile_Empty(t *testing.T) {
	pkgs, err := parseLockFile(nil)
	require.NoError(t, err)
	assert.Empty(t, pkgs)
}
